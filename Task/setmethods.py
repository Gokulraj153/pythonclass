sets = {10,20,30,40,50,70,80,100}
print(sets)
sets.add(70)
print(sets)
sets.remove(20)
print(sets)
sets.discard(30)
print(sets)
sets.update([20,30])
print(sets)
print()
set1 = {10,20,30,40,50,60,80,94,75}
